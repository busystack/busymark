import 'dart:async';
import 'dart:io';

import 'package:path/path.dart' as p;

import 'linux_atomic_file_api.dart';

class AtomicFileAlreadyExistsException implements Exception {
  const AtomicFileAlreadyExistsException(this.path);

  final String path;

  @override
  String toString() => 'A filesystem entity already exists at "$path".';
}

class AtomicFileChangedException implements Exception {
  const AtomicFileChangedException(this.path, {this.recoveryPath, this.cause});

  final String path;
  final String? recoveryPath;
  final Object? cause;

  @override
  String toString() {
    final recovery = recoveryPath == null
        ? ''
        : ' The displaced version was preserved at "$recoveryPath".';
    final detail = cause == null ? '' : ' Validation failed: $cause.';
    return 'The file at "$path" changed during publication.$recovery$detail';
  }
}

/// Publishes generated bytes without ever exposing a partially written file.
class AtomicFileWriter {
  const AtomicFileWriter();

  Future<void> writeBytes(
    String targetPath,
    List<int> bytes, {
    required bool overwrite,
    FutureOr<void> Function()? beforePublish,
    FutureOr<bool> Function(String replacedPath)? acceptReplaced,
  }) async {
    if (!Platform.isLinux) {
      throw UnsupportedError(
        'Atomic export is currently supported on Linux only.',
      );
    }
    final absoluteTarget = p.normalize(p.absolute(targetPath));
    final parent = Directory(p.dirname(absoluteTarget));
    if (!await parent.exists()) {
      throw FileSystemException(
        'The export destination directory does not exist',
        parent.path,
      );
    }

    final stagingDirectory = await parent.createTemp('.busymark-export-');
    final stagedFile = File(p.join(stagingDirectory.path, 'document.bin'));
    var preserveStagedFile = false;
    try {
      await stagedFile.writeAsBytes(bytes, flush: true);
      await beforePublish?.call();
      if (overwrite) {
        final targetType = await FileSystemEntity.type(
          absoluteTarget,
          followLinks: false,
        );
        if (targetType != FileSystemEntityType.notFound &&
            targetType != FileSystemEntityType.file) {
          throw FileSystemException(
            'The export destination is not a regular file',
            absoluteTarget,
          );
        }
        if (acceptReplaced != null) {
          if (targetType == FileSystemEntityType.notFound) {
            final errorNumber = LinuxAtomicFileApi.instance.publishNoReplace(
              stagedFile.absolute.path,
              absoluteTarget,
            );
            if (errorNumber == null) return;
            if (errorNumber == LinuxAtomicFileApi.fileExistsError) {
              throw AtomicFileChangedException(absoluteTarget);
            }
            throw FileSystemException(
              'Failed to atomically publish the new file',
              absoluteTarget,
              OSError('no-replace publication failed', errorNumber),
            );
          }
          final atomicApi = LinuxAtomicFileApi.instance;
          if (!atomicApi.isAvailable) {
            throw FileSystemException(
              'Conflict-safe replacement requires Linux renameat2',
              absoluteTarget,
            );
          }
          final exchangeError = atomicApi.exchange(
            stagedFile.absolute.path,
            absoluteTarget,
          );
          if (exchangeError != null) {
            throw AtomicFileChangedException(absoluteTarget);
          }
          Object? callbackError;
          var accepted = false;
          try {
            accepted = await acceptReplaced(stagedFile.absolute.path);
          } on Object catch (error) {
            callbackError = error;
          }
          if (!accepted || callbackError != null) {
            // Once the exchange has completed, [absoluteTarget] can be
            // changed again while the asynchronous validation is running.
            // A second exchange would then overwrite that newer version and
            // the normal staging cleanup would delete it. Ownership is
            // uncertain here, so leave the destination alone and retain the
            // displaced bytes for explicit recovery.
            preserveStagedFile = true;
            throw AtomicFileChangedException(
              absoluteTarget,
              recoveryPath: stagedFile.absolute.path,
              cause: callbackError,
            );
          }
          return;
        }
        await stagedFile.rename(absoluteTarget);
        return;
      }

      final errorNumber = LinuxAtomicFileApi.instance.publishNoReplace(
        stagedFile.absolute.path,
        absoluteTarget,
      );
      if (errorNumber == null) {
        return;
      }
      if (errorNumber == LinuxAtomicFileApi.fileExistsError) {
        throw AtomicFileAlreadyExistsException(absoluteTarget);
      }
      throw FileSystemException(
        'Failed to atomically publish the exported file',
        absoluteTarget,
        OSError('no-replace publication failed', errorNumber),
      );
    } finally {
      if (!preserveStagedFile) await _deleteBestEffort(stagedFile);
      try {
        if (!preserveStagedFile && await stagingDirectory.exists()) {
          await stagingDirectory.delete();
        }
      } on Object {
        // Cleanup must not hide the write result.
      }
    }
  }

  Future<void> _deleteBestEffort(File file) async {
    try {
      if (await file.exists()) {
        await file.delete();
      }
    } on Object {
      // Cleanup must not hide the write result.
    }
  }
}
